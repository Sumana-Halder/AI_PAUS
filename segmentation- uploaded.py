class DiceMonitor(Callback):
    def __init__(self, X_val, y_val, save_path, save_vessels, save_cortex, check_every=2):
        super().__init__(); self.X, self.y = X_val, y_val.astype(np.int32)
        self.save_path, self.save_vessels, self.save_cortex = save_path, save_vessels, save_cortex
        self.check_every = check_every; self.best_mean_fg = 0.0
        self.best_vessels_dice = 0.0; self.best_cortex_dice = 0.0
        self.best_dice_per_class = [0.0]*N_CLASSES; self.dice_history, self.loss_history = [], []; self._ge = 0
    def on_epoch_end(self, epoch, logs=None):
        self._ge += 1; logs = logs or {}
        self.loss_history.append(logs.get('loss', 0))
        print(f'  ep{self._ge:03d}  loss={logs.get("loss",0):.4f}  acc={logs.get("accuracy",0):.4f}  '
              f'val_loss={logs.get("val_loss",0):.4f}  val_acc={logs.get("val_accuracy",0):.4f}')
        if self._ge % self.check_every != 0: return
        probs = self.model.predict(self.X, verbose=0); preds = np.argmax(probs, axis=-1)
