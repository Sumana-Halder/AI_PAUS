# SECTION 8 -- SEGMENTATION LOSS
# =====================================================================
def per_class_tversky(y_sparse, y_pred):
    y_oh = tf.one_hot(tf.cast(y_sparse, tf.int32), depth=N_CLASSES); losses = []
    for c in range(N_CLASSES):
        tp = tf.reduce_sum(y_oh[..., c] * y_pred[..., c])
        fp = tf.reduce_sum((1 - y_oh[..., c]) * y_pred[..., c])
        fn = tf.reduce_sum(y_oh[..., c] * (1 - y_pred[..., c]))
        t  = (tp + 1e-7) / (tp + 0.20*fp + 0.80*fn + 1e-7)
        losses.append(1.0 - t)
    return losses

def focal_ce_per_class(y_sparse, y_pred, gamma=2.0):
    y_oh   = tf.one_hot(tf.cast(y_sparse, tf.int32), depth=N_CLASSES)
    ce_all = -tf.math.log(y_pred + 1e-7)
    focal  = tf.pow(1.0 - tf.exp(-ce_all), gamma) * ce_all
    return [tf.reduce_mean(y_oh[..., c] * focal[..., c]) for c in range(N_CLASSES)]

def grouped_seg_loss(y_sparse, y_pred):
    tv = per_class_tversky(y_sparse, y_pred); fc = focal_ce_per_class(y_sparse, y_pred)
    loss_per_class = [tv[c] + 0.35*fc[c] for c in range(N_CLASSES)]
    g_bg, g_skin, g_medulla = loss_per_class[0], loss_per_class[1], loss_per_class[2]
    g_deep = (loss_per_class[3] + loss_per_class[4]) / 2.0
    return (W_GROUP_BG*g_bg + W_GROUP_SKIN*g_skin + W_GROUP_MEDULLA*g_medulla + W_GROUP_DEEP*g_deep)

