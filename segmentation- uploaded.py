def fluence_metrics(ref, tst):
    """ref = FVM fluence, tst = PINN fluence, both normalised to [0,1]."""
    ref = np.asarray(ref, np.float64); tst = np.asarray(tst, np.float64)
    r, t = ref.ravel(), tst.ravel()
    mse   = np.mean((r - t)**2)
    nrmse = np.sqrt(mse)/(r.max() - r.min() + 1e-16)
    ssim_v = sk_ssim(tst, ref, data_range=1.0, gaussian_weights=True, sigma=1.5, use_sample_covariance=False)
    psnr_v = 10*np.log10(1.0/(mse + 1e-16))
    pear   = np.corrcoef(r, t)[0, 1] if r.std() > 0 and t.std() > 0 else np.nan
    mape   = 100*np.mean(np.abs(r - t)/np.maximum(np.abs(r), MAPE_FLOOR))
    return dict(NRMSE=nrmse, SSIM=ssim_v, PSNR_dB=psnr_v, Pearson_r=pear, MAPE_pct=mape)

