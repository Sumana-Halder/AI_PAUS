def pad16(arr, dims=(1, 2)):
    out = arr
    for d in dims:
        r = out.shape[d] % 16
        if r != 0:
            ps = [(0, 0)] * out.ndim; ps[d] = (0, 16 - r)
            out = np.pad(out, ps, mode='constant')
    return out

