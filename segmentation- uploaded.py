def augment_sample(img, lbl, epoch):
    if np.random.rand() > 0.5: img, lbl = np.fliplr(img).copy(), np.fliplr(lbl).copy()
    if np.random.rand() > 0.70: img, lbl = np.flipud(img).copy(), np.flipud(lbl).copy()
    if np.random.rand() > 0.5: img = np.clip(img * np.random.uniform(0.75, 1.25), 0, 1)
    if np.random.rand() > 0.5: img = np.power(np.clip(img, 1e-6, 1.0), np.random.uniform(0.70, 1.40))
    if np.random.rand() > 0.5: img = np.clip(img + np.random.randn(*img.shape) * 0.012, 0, 1)
    has_vessels = int((lbl == 4).sum()) > 8
    if epoch >= 25 and not has_vessels and np.random.rand() > 0.50:
        h_, w_ = img.shape
        dx_ = ndimage.gaussian_filter(np.random.randn(h_, w_) * 12, 4)
        dy_ = ndimage.gaussian_filter(np.random.randn(h_, w_) * 12, 4)
        gx, gy = np.meshgrid(np.arange(w_), np.arange(h_))
        map_x = np.clip(gx + dx_, 0, w_ - 1).astype('float32')
        map_y = np.clip(gy + dy_, 0, h_ - 1).astype('float32')
        img = cv2.remap(img.astype('float32'), map_x, map_y, cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT_101)
        lbl = cv2.remap(lbl.astype('float32'), map_x, map_y, cv2.INTER_NEAREST, borderMode=cv2.BORDER_REFLECT_101).astype(np.int32)
    if epoch >= 25:
        for cls_id, strength in [(1, 0.10), (3, 0.14), (4, 0.20)]:
            if np.random.rand() > 0.5:
                edge = cv2.Canny((lbl == cls_id).astype(np.uint8) * 255, 40, 120)
                img[edge > 0] = np.clip(img[edge > 0] + strength, 0, 1)
    if epoch >= 25 and not has_vessels and np.random.rand() > 0.60:
        angle = np.random.uniform(-10, 10); h_, w_ = img.shape
        M = cv2.getRotationMatrix2D((w_ // 2, h_ // 2), angle, 1.0)
        img = cv2.warpAffine(img, M, (w_, h_), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT_101)
        lbl = cv2.warpAffine(lbl.astype('float32'), M, (w_, h_), flags=cv2.INTER_NEAREST,
                              borderMode=cv2.BORDER_REFLECT_101).astype(np.int32)
    return img, lbl

def build_sampling_weights(y, epoch):
    n = len(y); t = epoch / max(EPOCHS - 1, 1)
    vessel_mult = 20.0 + 10.0*t; cortex_mult = 10.0 + 8.0*t
    weights = np.ones(n, dtype=np.float64)
    for i in range(n):
        lbl = y[i]
        vr = np.sum(lbl == 4)/lbl.size; cr = np.sum(lbl == 3)/lbl.size
        sr = np.sum(lbl == 1)/lbl.size; mr = np.sum(lbl == 2)/lbl.size
        weights[i] = 1.0 + sr*4 + mr*2.5 + cr*cortex_mult + vr*vessel_mult
    return weights / weights.sum()

def data_generator(X_us, y_lbl, batch_size, epoch):
    n = len(X_us); indices = np.arange(n); weights = build_sampling_weights(y_lbl, epoch)
    while True:
        chosen = np.random.choice(indices, size=batch_size, p=weights)
        X_batch = np.zeros((batch_size, H, W, 1), dtype=np.float32)
        y_batch = np.zeros((batch_size, H, W), dtype=np.int32)
        for j, idx in enumerate(chosen):
            img, lbl = X_us[idx, :, :, 0].copy(), y_lbl[idx].copy()
            img, lbl = augment_sample(img, lbl, epoch)
            X_batch[j, :, :, 0] = img; y_batch[j] = lbl
        yield X_batch, y_batch.astype(np.int32)

