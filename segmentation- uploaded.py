# SECTION 9 -- ATTENTION U-NET (Residual + CBAM + ASPP)
# =====================================================================
def conv_bn_relu(x, f, dilation=1):
    x = Conv2D(f, 3, padding='same', dilation_rate=dilation, kernel_initializer='he_normal')(x)
    x = BatchNormalization()(x); return Activation('relu')(x)

def res_block(x, f):
    shortcut = BatchNormalization()(Conv2D(f, 1, padding='same', kernel_initializer='he_normal')(x))
    x = conv_bn_relu(x, f); x = conv_bn_relu(x, f)
    return Activation('relu')(Add()([x, shortcut]))

def channel_attention(x, ratio=8):
    c = x.shape[-1]; r = max(c // ratio, 4)
    ga = Dense(r, activation='relu')(GlobalAveragePooling2D()(x)); ga = Dense(c)(ga)
    gm = Dense(r, activation='relu')(GlobalMaxPooling2D()(x));     gm = Dense(c)(gm)
    gate = Reshape((1, 1, c))(Activation('sigmoid')(Add()([ga, gm])))
    return Multiply()([x, gate])

def spatial_attention(x):
    avg  = Lambda(lambda t: tf.reduce_mean(t, axis=-1, keepdims=True))(x)
    mx   = Lambda(lambda t: tf.reduce_max(t,  axis=-1, keepdims=True))(x)
    comb = Lambda(lambda ts: tf.concat(ts, axis=-1))([avg, mx])
    att  = Conv2D(1, 7, padding='same', activation='sigmoid', kernel_initializer='glorot_uniform')(comb)
    return Multiply()([x, att])

def cbam(x, ratio=8): return spatial_attention(channel_attention(x, ratio))

def aspp(x, f):
    b1 = Activation('relu')(BatchNormalization()(Conv2D(f, 1, padding='same')(x)))
    b2 = Activation('relu')(BatchNormalization()(Conv2D(f, 3, padding='same', dilation_rate=2)(x)))
    b3 = Activation('relu')(BatchNormalization()(Conv2D(f, 3, padding='same', dilation_rate=4)(x)))
    b4 = Activation('relu')(BatchNormalization()(Conv2D(f, 3, padding='same', dilation_rate=8)(x)))
    b5 = Activation('relu')(BatchNormalization()(Conv2D(f, 3, padding='same', dilation_rate=12)(x)))
    m  = concatenate([b1, b2, b3, b4, b5])
    return Activation('relu')(BatchNormalization()(Conv2D(f, 1, padding='same')(m)))

def attention_gate(x, g, f):
    tx = Conv2D(f, 1, padding='same')(x); tg = Conv2D(f, 1, padding='same')(g)
    comb = Activation('relu')(Add()([tx, tg]))
    alpha = Conv2D(1, 1, padding='same', activation='sigmoid')(comb)
    return Multiply()([x, alpha])

def build_model(n_cls, img_h, img_w, n_ch=1):
    inp = Input((img_h, img_w, n_ch))
    e1 = cbam(res_block(inp, 32),  ratio=4); p1 = MaxPooling2D(2)(e1)
    e2 = cbam(res_block(p1,  64),  ratio=8); p2 = MaxPooling2D(2)(e2)
    e3 = cbam(res_block(p2,  128), ratio=8); p3 = MaxPooling2D(2)(e3)
    e4 = cbam(res_block(p3,  256), ratio=8); p4 = MaxPooling2D(2)(e4)
    b5 = conv_bn_relu(p4, 512); b5 = SpatialDropout2D(0.30)(b5); b5 = cbam(aspp(b5, 512), ratio=8)
    u6 = UpSampling2D(2)(b5); a6 = attention_gate(e4, u6, 256); d6 = res_block(concatenate([u6, a6]), 256)
    u7 = UpSampling2D(2)(d6); a7 = attention_gate(e3, u7, 128); d7 = res_block(concatenate([u7, a7]), 128)
    u8 = UpSampling2D(2)(d7); a8 = attention_gate(e2, u8, 64);  d8 = res_block(concatenate([u8, a8]), 64)
    u9 = UpSampling2D(2)(d8); a9 = attention_gate(e1, u9, 32);  d9 = res_block(concatenate([u9, a9]), 32)
    out = Conv2D(n_cls, 1, activation='softmax')(d9)
    return Model(inp, out)

