class SegModel(tf.keras.Model):
    def __init__(self, backbone):
        super().__init__(); self.backbone = backbone
        self.loss_tracker = Mean(name='loss'); self.acc_tracker = SparseCategoricalAccuracy(name='accuracy')
    def call(self, inputs, training=False): return self.backbone(inputs, training=training)
    def train_step(self, data):
        x, y_sparse = data
        with tf.GradientTape() as tape:
            y_pred = self(x, training=True); loss = grouped_seg_loss(y_sparse, y_pred)
        grads = tape.gradient(loss, self.trainable_variables)
        self.optimizer.apply_gradients(zip(grads, self.trainable_variables))
        self.loss_tracker.update_state(loss); self.acc_tracker.update_state(y_sparse, y_pred)
        return {'loss': self.loss_tracker.result(), 'accuracy': self.acc_tracker.result()}
    def test_step(self, data):
        x, y_sparse = data; y_pred = self(x, training=False); loss = grouped_seg_loss(y_sparse, y_pred)
        self.loss_tracker.update_state(loss); self.acc_tracker.update_state(y_sparse, y_pred)
        return {'loss': self.loss_tracker.result(), 'accuracy': self.acc_tracker.result()}
    @property
    def metrics(self): return [self.loss_tracker, self.acc_tracker]

