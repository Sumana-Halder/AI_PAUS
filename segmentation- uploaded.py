def fvm_diffusion(mua, musr, src, h=DX, A_refl=1.0):
    """Full-grid cell-centred FVM: -div(D grad phi) + mu_a phi = S.
       Robin leak at top/bottom, reflective side walls."""
    D = np.minimum(1.0/(3.0*(mua+musr)), D_MAX)
    n = Nz*Nx; idx = np.arange(n).reshape(Nz, Nx)
    harm = lambda a, b: 2*a*b/(a+b)
    diag = (mua*h*h).ravel().copy()
    rows, cols, vals = [], [], []
    a = idx[:, :-1].ravel(); b = idx[:, 1:].ravel(); c = harm(D[:, :-1], D[:, 1:]).ravel()
    rows += [a, b]; cols += [b, a]; vals += [-c, -c]; diag[a] += c; diag[b] += c
    a = idx[:-1, :].ravel(); b = idx[1:, :].ravel(); c = harm(D[:-1, :], D[1:, :]).ravel()
    rows += [a, b]; cols += [b, a]; vals += [-c, -c]; diag[a] += c; diag[b] += c
    diag[idx[0, :]]  += h/(0.5*h/D[0, :]  + 2.0*A_refl)
    diag[idx[-1, :]] += h/(0.5*h/D[-1, :] + 2.0*A_refl)
    A = (coo_matrix((np.concatenate(vals), (np.concatenate(rows), np.concatenate(cols))), shape=(n, n)).tocsr()
         + diags(diag)).tocsc()
    bvec = (src*h*h).ravel()
    return A, bvec, spsolve(A, bvec)

def pinn_refine(phi_fvm, A, bvec):
    """PINN field: minimise row-normalised diffusion residual over log(phi) with Adam.
       Starts from a blurred FVM field; best iterate kept. Returns (phi, loss_history)."""
    try:
        import tensorflow as tf
    except ImportError:
        return phi_fvm, []
    sc   = float(phi_fvm.max())
    init = imgaussfilt(phi_fvm.reshape(Nz, Nx), PINN_INIT_BLUR).ravel()
    Ac = A.tocoo()
    Sp = tf.sparse.reorder(tf.sparse.SparseTensor(np.stack([Ac.row, Ac.col], 1).astype(np.int64),
                                                  Ac.data.astype(np.float32), Ac.shape))
    bt  = tf.constant((bvec/sc).astype(np.float32)[:, None])
    inv = tf.constant((1.0/A.diagonal()).astype(np.float32)[:, None])
    u   = tf.Variable(np.log(np.maximum(init/sc, 1e-12)).astype(np.float32)[:, None])
    opt = tf.keras.optimizers.Adam(learning_rate=PINN_LR)
    hist, best, best_u = [], np.inf, u.numpy().copy()
    for _ in range(PINN_STEPS):
        with tf.GradientTape() as tape:
            loss = tf.reduce_mean(((tf.sparse.sparse_dense_matmul(Sp, tf.exp(u)) - bt)*inv)**2)
        lv = float(loss.numpy()); hist.append(lv)
        if lv < best: best, best_u = lv, u.numpy().copy()
        opt.apply_gradients(zip(tape.gradient(loss, [u]), [u]))
    return np.exp(best_u[:, 0])*sc, hist

def fluence_gain(wl, P):
    mua, musr = optical_maps(wl, P)
    mutr = mua + musr
    I = I0[None, :]*np.exp(-(np.cumsum(mutr*DX, 0) - 0.5*mutr*DX))
    A, bvec, phi_f = fvm_diffusion(mua, musr, musr*I)
    phi_p, hist = (pinn_refine(phi_f, A, bvec) if USE_PINN_REFINE else (phi_f, []))

    def finish(v):
        return imgaussfilt(v.reshape(Nz, Nx) + I, FLU_SMOOTH)
    phi_fvm_n = finish(phi_f);  phi_fvm_n  /= phi_fvm_n.max() + 1e-12
    phi_pinn  = finish(phi_p);  phi_pinn_n = phi_pinn/(phi_pinn.max() + 1e-12)

    sc  = float(phi_p.max())
    res = imgaussfilt((np.abs(A @ phi_p - bvec)/A.diagonal()/sc).reshape(Nz, Nx), 1.0)

    phi_use = phi_pinn_n if USE_PINN_REFINE else phi_fvm_n
    gain = (1.0/np.maximum(phi_use, 1.0/MAX_GAIN))**GAIN_ALPHA
    return gain, phi_use, dict(phi_fvm=phi_fvm_n, phi_pinn=phi_pinn_n, resid=res, hist=hist)

up_cubic = lambda g: cv2.resize(g.astype(np.float32), (NxH, NzH), interpolation=cv2.INTER_CUBIC)

# ----------------------------- CORRECTION + SEG PRIOR -----------------------------
def norm_corr(x, gamma):
    lo, hi = prctile(x.ravel(), 1), prctile(x.ravel(), 99)
    return np.clip((x-lo)/(hi-lo+1e-16), 0, 1)**gamma

def apply_seg_prior(pa_corr, cls_masks):
    U = UPSCALE
    pa_bg  = imgaussfilt(pa_corr, 8*U)
    pa_mix = 0.5*mat2gray(pa_corr) + 0.5*mat2gray(pa_corr/(pa_bg+0.05))
    score = np.zeros((NzH, NxH, len(cls_masks)+1)); score[..., 0] = 0.5
    for i, m in enumerate(cls_masks):
        score[..., i+1] = cv2.resize(imgaussfilt(m.astype(np.float64), 0.7).astype(np.float32),
                                     (NxH, NzH), interpolation=cv2.INTER_CUBIC)
    ci = score.argmax(-1)
    regions = [ci == 1, ci == 2, ci == 3, ci == 4, ci == 5]; tissue_h = ci > 0
    pa_n = np.zeros((NzH, NxH))
    for mk in regions:
        if mk.sum() < 10: continue
        v = pa_mix[mk]; lo, hi = prctile(v, 2), prctile(v, 98)
        pa_n[mk] = np.clip((v-lo)/(hi-lo+1e-16), 0, 1)
    pa_n = np.clip(pa_n + SP['SHARP_PA_AMT']*(pa_n - imgaussfilt(pa_n, SP['SHARP_PA_SIG'])), 0, 1)
    level = np.zeros((NzH, NxH)); tex = np.zeros((NzH, NxH))
    for mk, nm in zip(regions, ['skin', 'cortex', 'medulla', 'tract', 'vessel']):
        level[mk] = LVL[nm]; tex[mk] = TEX[nm]
    level, tex = imgaussfilt(level, 0.6), imgaussfilt(tex, 0.6)
    out = level*((1-tex) + tex*pa_n); out[~tissue_h] = 0
    f = out/0.35
    f = f + SP['SHARP_OUT_AMT']*(f - imgaussfilt(f, SP['SHARP_OUT_SIG'])); f[~tissue_h] = 0
    return np.clip(f, 0, 1)*0.35

# ----------------------------- REGISTRATION -----------------------------
def register_stack(pa_stack, us_stack, ref_k):
    n = pa_stack.shape[2]
    valid = np.ones(pa_stack.shape, bool)
    win = cv2.createHanningWindow((NxH, NzH), cv2.CV_32F)
    ncc = lambda a, b: float(np.corrcoef(a.ravel(), b.ravel())[0, 1])
    ref_img = us_stack[:, :, ref_k].astype(np.float32)
    for k in range(n):
        if k == ref_k: continue
        mov = us_stack[:, :, k].astype(np.float32)
        (ddx, ddy), _ = cv2.phaseCorrelate(ref_img, mov, win)
        best = None
        for sgn in (-1.0, 1.0):
            M = np.float32([[1, 0, sgn*ddx], [0, 1, sgn*ddy]])
            w = cv2.warpAffine(mov, M, (NxH, NzH), flags=cv2.INTER_LINEAR,
                               borderMode=cv2.BORDER_CONSTANT, borderValue=0)
            sc = ncc(w, ref_img)
            if best is None or sc > best[0]: best = (sc, M, sgn)
        _, M, sgn = best
        if abs(sgn*ddx/UPSCALE) > MAX_SHIFT or abs(sgn*ddy/UPSCALE) > MAX_SHIFT:
            print(f'   frame idx {k} skipped (shift too large)'); continue
        wrp = lambda a: cv2.warpAffine(a.astype(np.float32), M, (NxH, NzH), flags=cv2.INTER_LINEAR,
                                       borderMode=cv2.BORDER_CONSTANT, borderValue=0)
        pa_stack[:, :, k] = wrp(pa_stack[:, :, k]); us_stack[:, :, k] = wrp(us_stack[:, :, k])
        valid[:, :, k] = wrp(np.ones((NzH, NxH))) > 0.99
    return pa_stack, us_stack, valid

# ----------------------------- RUN -----------------------------
def run_single(f, wl):
    pa, us = load_frame(f)
    P = build_prior(f, us)
    gain, phi, diag = fluence_gain(wl, P)
    pa_corr = pa*up_cubic(gain)
    return dict(raw=mat2gray(pa), corr=norm_corr(pa_corr, GAMMA_PA),
                final=apply_seg_prior(pa_corr, P['cls_masks']), phi=phi, diag=diag)

def run_avg(frames, wl_range):
    n = len(frames); wls = np.linspace(wl_range[0], wl_range[1], n)
    ref_k = n//2 if n > 2 else n-1
    pa_stack = np.zeros((NzH, NxH, n)); us_stack = np.zeros((NzH, NxH, n))
    for k, f in enumerate(frames):
        pa_stack[:, :, k], us_stack[:, :, k] = load_frame(f)
    P = build_prior(frames[ref_k], us_stack[:, :, ref_k])
    pa_stack, us_stack, valid = register_stack(pa_stack, us_stack, ref_k)
    vcnt = np.maximum(valid.sum(2), 1); vf = valid.astype(np.float64)
    gain_hr = np.zeros((NzH, NxH, n)); diags_ = []
    for k in range(n):
        g, p, d = fluence_gain(wls[k], P); gain_hr[:, :, k] = up_cubic(g); diags_.append(d)
    pa_raw  = (pa_stack*vf).sum(2)/vcnt
    pa_corr = (pa_stack*gain_hr*vf).sum(2)/vcnt
    return dict(raw=mat2gray(pa_raw), corr=norm_corr(pa_corr, GAMMA_PA),
                final=apply_seg_prior(pa_corr, P['cls_masks']), diags=diags_), wls

