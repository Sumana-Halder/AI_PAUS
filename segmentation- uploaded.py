def correct_motion(imgs, pa, lbls):
    ref = (imgs[0] * 255).astype('float32')
    imgs_out, pa_out, lbls_out = np.zeros_like(imgs), np.zeros_like(pa), np.zeros_like(lbls)
    imgs_out[0], pa_out[0], lbls_out[0] = imgs[0], pa[0], lbls[0]
    max_shift = 0.0
    for i in range(1, len(imgs)):
        frame = (imgs[i] * 255).astype('float32')
        (dx, dy), _ = cv2.phaseCorrelate(ref, frame)
        max_shift = max(max_shift, math.sqrt(dx**2 + dy**2))
        M = np.float32([[1, 0, -dx], [0, 1, -dy]])
        imgs_out[i] = cv2.warpAffine(imgs[i], M, (W, H), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT_101)
        pa_out[i]   = cv2.warpAffine(pa[i], M, (W, H), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT_101)
        lbls_out[i] = cv2.warpAffine(lbls[i].astype('float32'), M, (W, H), flags=cv2.INTER_NEAREST,
                                      borderMode=cv2.BORDER_REFLECT_101).astype(np.int32)
    print(f'Motion correction done. Max shift: {max_shift:.1f}px')
    return imgs_out, pa_out, lbls_out

